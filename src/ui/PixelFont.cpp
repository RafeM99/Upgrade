struct Glyph { int cp; std::vector<std::string> rows; int w; };

std::vector<Glyph> parse()
{
    std::vector<Glyph> out;
    out.push_back({' ', {}, 3});
    const char* p = kGlyphs;
    Glyph* cur = nullptr;
    while (*p) {
        const char* e = std::strchr(p, '\n');
        std::string line = e ? std::string(p, e - p) : std::string(p);
        p = e ? e + 1 : p + line.size();
        if (line.size() == 2 && line[0] == '=') {
            out.push_back({(unsigned char)line[1], {}, 1});
            cur = &out.back();
        } else if (cur && !line.empty()) {
            cur->rows.push_back(line);
            cur->w = std::max(cur->w, (int)line.size());
        }
    }
    // typographic quote marks drawn as the plain ones, in case the text has them
    auto copyOf = [&](int from, int cp) {
        for (size_t i = 0; i < out.size(); ++i)
            if (out[i].cp == from) { Glyph g = out[i]; g.cp = cp; out.push_back(g); return; }
    };
    copyOf('\'', 0x2018); copyOf('\'', 0x2019); copyOf('\'', 0xB4);
    copyOf('"', 0x201C); copyOf('"', 0x201D);
    copyOf('-', 0x2013); copyOf('-', 0x2014);
    copyOf('.', 0xB7);
    return out;
}

